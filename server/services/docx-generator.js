/**
 * DOCX generator — converts markdown to branded NCI/EAGLE Word documents.
 * Uses docx library for DOCX generation and marked for markdown parsing.
 */

import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  Table,
  TableRow,
  TableCell,
  WidthType,
  AlignmentType,
  HeadingLevel,
  BorderStyle,
  ShadingType,
  Header,
  Footer,
  PageNumber,
  NumberFormat,
  convertInchesToTwip,
  LevelFormat,
  TableLayoutType,
} from "docx";
import { marked } from "marked";

// NCI branding constants
const NCI_BLUE = "003366";
const LIGHT_BLUE = "E8F0FE";
const WHITE = "FFFFFF";
const GRAY = "808080";
const BLACK = "000000";

const HEADING_SIZES = { 1: 36, 2: 32, 3: 28, 4: 24 }; // half-points

/**
 * Generate a branded DOCX from markdown text.
 *
 * @param {string} markdownText - Source markdown content
 * @param {object} options
 * @param {string} options.title - Document title for header
 * @param {string} [options.docType] - Document type
 * @param {boolean} [options.isDraft=true] - Show DRAFT watermark
 * @param {string} [options.date] - Date string for header
 * @returns {Promise<Buffer>} DOCX buffer
 */
export async function generateDocx(markdownText, options = {}) {
  const {
    title = "Document",
    isDraft = true,
    date = new Date().toLocaleDateString("en-US", {
      year: "numeric",
      month: "long",
      day: "numeric",
    }),
  } = options;

  const tokens = marked.lexer(markdownText);
  const children = buildDocxContent(tokens);

  // Build header with optional DRAFT watermark
  const headerChildren = [
    new Paragraph({
      alignment: AlignmentType.CENTER,
      children: [
        new TextRun({
          text: `EAGLE — ${title}`,
          size: 18, // 9pt
          color: GRAY,
          font: "Calibri",
        }),
      ],
      border: {
        bottom: { style: BorderStyle.SINGLE, size: 6, color: NCI_BLUE },
      },
      spacing: { after: 200 },
    }),
  ];

  // Add DRAFT watermark via a large, light-gray text in the header
  if (isDraft) {
    headerChildren.push(
      new Paragraph({
        alignment: AlignmentType.CENTER,
        children: [
          new TextRun({
            text: "DRAFT",
            size: 120, // 60pt
            color: "D0D0D0",
            font: "Calibri",
            bold: true,
          }),
        ],
      })
    );
  }

  const doc = new Document({
    title,
    creator: "EAGLE — NCI Acquisition Assistant",
    description: `Generated by EAGLE on ${date}`,
    styles: {
      paragraphStyles: [
        {
          id: "Heading1",
          name: "Heading 1",
          basedOn: "Normal",
          next: "Normal",
          run: { size: HEADING_SIZES[1], bold: true, color: NCI_BLUE, font: "Calibri" },
          paragraph: { spacing: { before: 240, after: 120 } },
        },
        {
          id: "Heading2",
          name: "Heading 2",
          basedOn: "Normal",
          next: "Normal",
          run: { size: HEADING_SIZES[2], bold: true, color: NCI_BLUE, font: "Calibri" },
          paragraph: { spacing: { before: 200, after: 100 } },
        },
        {
          id: "Heading3",
          name: "Heading 3",
          basedOn: "Normal",
          next: "Normal",
          run: { size: HEADING_SIZES[3], bold: true, color: NCI_BLUE, font: "Calibri" },
          paragraph: { spacing: { before: 160, after: 80 } },
        },
        {
          id: "Heading4",
          name: "Heading 4",
          basedOn: "Normal",
          next: "Normal",
          run: { size: HEADING_SIZES[4], bold: true, color: NCI_BLUE, font: "Calibri" },
          paragraph: { spacing: { before: 120, after: 60 } },
        },
      ],
    },
    numbering: {
      config: [
        {
          reference: "eagle-bullets",
          levels: [
            {
              level: 0,
              format: LevelFormat.BULLET,
              text: "\u2022",
              alignment: AlignmentType.LEFT,
              style: { paragraph: { indent: { left: 720, hanging: 360 } } },
            },
          ],
        },
        {
          reference: "eagle-numbering",
          levels: [
            {
              level: 0,
              format: LevelFormat.DECIMAL,
              text: "%1.",
              alignment: AlignmentType.LEFT,
              style: { paragraph: { indent: { left: 720, hanging: 360 } } },
            },
          ],
        },
      ],
    },
    sections: [
      {
        properties: {
          page: {
            margin: {
              top: convertInchesToTwip(1),
              bottom: convertInchesToTwip(1),
              left: convertInchesToTwip(1),
              right: convertInchesToTwip(1),
            },
            pageNumbers: { start: 1 },
          },
        },
        headers: {
          default: new Header({ children: headerChildren }),
        },
        footers: {
          default: new Footer({
            children: [
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: [
                  new TextRun({
                    text: "Generated by EAGLE — NCI Acquisition Assistant  |  Page ",
                    size: 16,
                    color: GRAY,
                    font: "Calibri",
                  }),
                  new TextRun({
                    children: [PageNumber.CURRENT],
                    size: 16,
                    color: GRAY,
                    font: "Calibri",
                  }),
                  new TextRun({
                    text: " of ",
                    size: 16,
                    color: GRAY,
                    font: "Calibri",
                  }),
                  new TextRun({
                    children: [PageNumber.TOTAL_PAGES],
                    size: 16,
                    color: GRAY,
                    font: "Calibri",
                  }),
                ],
                border: {
                  top: { style: BorderStyle.SINGLE, size: 6, color: NCI_BLUE },
                },
                spacing: { before: 200 },
              }),
            ],
          }),
        },
        children,
      },
    ],
  });

  return await Packer.toBuffer(doc);
}

function buildDocxContent(tokens) {
  const content = [];

  for (const token of tokens) {
    switch (token.type) {
      case "heading":
        content.push(buildHeading(token));
        break;
      case "paragraph":
        content.push(buildParagraph(token));
        break;
      case "table":
        content.push(buildTable(token));
        break;
      case "list":
        content.push(...buildList(token));
        break;
      case "hr":
        content.push(buildHr());
        break;
      case "space":
        content.push(new Paragraph({ spacing: { before: 100 } }));
        break;
      case "code":
        content.push(buildCodeBlock(token));
        break;
      case "blockquote":
        content.push(buildBlockquote(token));
        break;
      default:
        break;
    }
  }

  return content;
}

function buildHeading(token) {
  const depth = Math.min(token.depth, 4);
  const headingLevels = {
    1: HeadingLevel.HEADING_1,
    2: HeadingLevel.HEADING_2,
    3: HeadingLevel.HEADING_3,
    4: HeadingLevel.HEADING_4,
  };

  return new Paragraph({
    heading: headingLevels[depth],
    children: [
      new TextRun({
        text: token.text,
        bold: true,
        color: NCI_BLUE,
        size: HEADING_SIZES[depth],
        font: "Calibri",
      }),
    ],
  });
}

function buildParagraph(token) {
  const runs = token.tokens
    ? buildInlineRuns(token.tokens)
    : [new TextRun({ text: token.text || "", size: 22, font: "Calibri" })];

  return new Paragraph({
    children: runs,
    spacing: { after: 120, line: 312 }, // 1.3x line height (240 * 1.3)
  });
}

function buildInlineRuns(tokens) {
  const runs = [];
  for (const tok of tokens) {
    switch (tok.type) {
      case "text":
        runs.push(
          new TextRun({
            text: tok.text,
            size: 22, // 11pt
            font: "Calibri",
          })
        );
        break;
      case "strong":
        if (tok.tokens) {
          for (const child of buildInlineRuns(tok.tokens)) {
            // Clone with bold
            runs.push(
              new TextRun({
                ...extractRunProperties(child),
                bold: true,
              })
            );
          }
        } else {
          runs.push(
            new TextRun({
              text: tok.text,
              bold: true,
              size: 22,
              font: "Calibri",
            })
          );
        }
        break;
      case "em":
        if (tok.tokens) {
          for (const child of buildInlineRuns(tok.tokens)) {
            runs.push(
              new TextRun({
                ...extractRunProperties(child),
                italics: true,
              })
            );
          }
        } else {
          runs.push(
            new TextRun({
              text: tok.text,
              italics: true,
              size: 22,
              font: "Calibri",
            })
          );
        }
        break;
      case "codespan":
        runs.push(
          new TextRun({
            text: tok.text,
            font: "Courier New",
            size: 20,
            color: "505050",
            shading: { type: ShadingType.CLEAR, fill: "F5F5F5" },
          })
        );
        break;
      default:
        runs.push(
          new TextRun({
            text: tok.raw || tok.text || "",
            size: 22,
            font: "Calibri",
          })
        );
        break;
    }
  }
  return runs;
}

function extractRunProperties(run) {
  // Extract known properties from a TextRun for cloning
  const opts = run.root?.[1] || {};
  // Fallback: just get the text and common props
  return {
    text: opts.text || "",
    size: opts.size || 22,
    font: opts.font || "Calibri",
    bold: opts.bold || false,
    italics: opts.italics || false,
    color: opts.color,
  };
}

function buildTable(token) {
  const headers = token.header.map((cell) => cellText(cell));
  const rows = token.rows.map((row) => row.map((cell) => cellText(cell)));
  const colCount = headers.length;

  if (colCount === 0) return new Paragraph({});

  // Header row
  const headerRow = new TableRow({
    tableHeader: true,
    children: headers.map(
      (text) =>
        new TableCell({
          children: [
            new Paragraph({
              children: [
                new TextRun({
                  text,
                  bold: true,
                  color: WHITE,
                  size: 20,
                  font: "Calibri",
                }),
              ],
              alignment: AlignmentType.LEFT,
            }),
          ],
          shading: { type: ShadingType.CLEAR, fill: NCI_BLUE },
          margins: { top: 40, bottom: 40, left: 80, right: 80 },
        })
    ),
  });

  // Data rows
  const dataRows = rows.map(
    (row, rowIndex) =>
      new TableRow({
        children: row.map(
          (text) =>
            new TableCell({
              children: [
                new Paragraph({
                  children: [
                    new TextRun({
                      text,
                      size: 20,
                      font: "Calibri",
                    }),
                  ],
                }),
              ],
              shading: {
                type: ShadingType.CLEAR,
                fill: rowIndex % 2 === 0 ? WHITE : LIGHT_BLUE,
              },
              margins: { top: 30, bottom: 30, left: 80, right: 80 },
            })
        ),
      })
  );

  return new Table({
    rows: [headerRow, ...dataRows],
    width: { size: 100, type: WidthType.PERCENTAGE },
    layout: TableLayoutType.AUTOFIT,
  });
}

function cellText(cell) {
  if (typeof cell === "string") return cell;
  if (cell.text) return cell.text;
  if (cell.tokens) return cell.tokens.map((t) => t.text || t.raw || "").join("");
  return "";
}

function buildList(token) {
  const ordered = token.ordered;
  const items = token.items || [];
  const paragraphs = [];

  for (let i = 0; i < items.length; i++) {
    const item = items[i];
    let text = extractItemText(item);

    // Handle checkboxes
    if (item.checked === true) text = "☑ " + text;
    else if (item.checked === false) text = "☐ " + text;

    paragraphs.push(
      new Paragraph({
        children: [
          new TextRun({
            text,
            size: 22,
            font: "Calibri",
          }),
        ],
        numbering: {
          reference: ordered ? "eagle-numbering" : "eagle-bullets",
          level: 0,
        },
        spacing: { after: 60 },
      })
    );
  }

  return paragraphs;
}

function extractItemText(item) {
  if (item.tokens) {
    return item.tokens
      .map((t) => {
        if (t.type === "text") return t.text;
        if (t.type === "paragraph" && t.tokens) {
          return t.tokens.map((tt) => tt.text || tt.raw || "").join("");
        }
        return t.text || t.raw || "";
      })
      .join("");
  }
  return item.text || "";
}

function buildHr() {
  return new Paragraph({
    border: {
      bottom: { style: BorderStyle.SINGLE, size: 6, color: "C8C8C8" },
    },
    spacing: { before: 200, after: 200 },
  });
}

function buildCodeBlock(token) {
  return new Paragraph({
    children: [
      new TextRun({
        text: token.text || "",
        font: "Courier New",
        size: 18,
        color: "3C3C3C",
      }),
    ],
    shading: { type: ShadingType.CLEAR, fill: "F5F5F5" },
    spacing: { before: 100, after: 100 },
    indent: { left: 200, right: 200 },
  });
}

function buildBlockquote(token) {
  const text = token.tokens
    ? token.tokens.map((t) => t.text || t.raw || "").join("\n")
    : token.text || "";

  return new Paragraph({
    children: [
      new TextRun({
        text,
        italics: true,
        color: "505050",
        size: 22,
        font: "Calibri",
      }),
    ],
    border: {
      left: { style: BorderStyle.SINGLE, size: 12, color: NCI_BLUE },
    },
    indent: { left: 300 },
    spacing: { before: 100, after: 100 },
  });
}
