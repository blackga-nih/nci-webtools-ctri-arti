/**
 * PDF generator — converts markdown to branded NCI/EAGLE PDF documents.
 * Uses pdfkit for PDF generation and marked for markdown parsing.
 */

import { marked } from "marked";
import PDFDocument from "pdfkit";

// NCI branding constants
const NCI_BLUE = [0, 51, 102]; // #003366
const LIGHT_BLUE = [232, 240, 254]; // #E8F0FE
const WHITE = [255, 255, 255];
const GRAY = [128, 128, 128];
const LIGHT_GRAY = [200, 200, 200];
const BLACK = [0, 0, 0];

const PAGE_WIDTH = 612; // Letter: 8.5"
const PAGE_HEIGHT = 792; // Letter: 11"
const MARGIN = 72; // 1 inch
const CONTENT_WIDTH = PAGE_WIDTH - 2 * MARGIN; // 468pt
const HEADER_HEIGHT = 40;
const FOOTER_HEIGHT = 30;
const CONTENT_TOP = MARGIN + HEADER_HEIGHT + 10;
const CONTENT_BOTTOM = PAGE_HEIGHT - MARGIN - FOOTER_HEIGHT - 10;

const HEADING_SIZES = { 1: 18, 2: 16, 3: 14, 4: 12 };
const BODY_SIZE = 11;
const LINE_HEIGHT = 1.3;

/**
 * Generate a branded PDF from markdown text.
 *
 * @param {string} markdownText - Source markdown content
 * @param {object} options
 * @param {string} options.title - Document title for header
 * @param {string} [options.docType] - Document type
 * @param {boolean} [options.isDraft=true] - Show DRAFT watermark
 * @param {string} [options.date] - Date string for header
 * @returns {Promise<Buffer>} PDF buffer
 */
export async function generatePdf(markdownText, options = {}) {
  const {
    title = "Document",
    isDraft = true,
    date = new Date().toLocaleDateString("en-US", {
      year: "numeric",
      month: "long",
      day: "numeric",
    }),
  } = options;

  const tokens = marked.lexer(markdownText);

  return new Promise((resolve, reject) => {
    const chunks = [];
    const doc = new PDFDocument({
      size: "LETTER",
      margins: {
        top: CONTENT_TOP,
        bottom: PAGE_HEIGHT - CONTENT_BOTTOM,
        left: MARGIN,
        right: MARGIN,
      },
      bufferPages: true,
      autoFirstPage: true,
      info: {
        Title: title,
        Author: "EAGLE — NCI Acquisition Assistant",
        Creator: "EAGLE Document Generator",
      },
    });

    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    // Render content
    renderTokens(doc, tokens);

    // Add headers, footers, and watermarks to all pages
    const pageCount = doc.bufferedPageRange().count;
    for (let i = 0; i < pageCount; i++) {
      doc.switchToPage(i);
      drawHeader(doc, title, date);
      drawFooter(doc, i + 1, pageCount);
      if (isDraft) drawWatermark(doc);
    }

    doc.end();
  });
}

function drawHeader(doc, title, date) {
  doc.save();
  const headerText = `EAGLE  |  ${title}  |  ${date}`;
  doc.fontSize(8).fillColor(GRAY).text(headerText, MARGIN, MARGIN, {
    width: CONTENT_WIDTH,
    align: "center",
    lineBreak: false,
  });
  // NCI blue line under header
  doc
    .moveTo(MARGIN, MARGIN + 18)
    .lineTo(PAGE_WIDTH - MARGIN, MARGIN + 18)
    .strokeColor(NCI_BLUE)
    .lineWidth(1.5)
    .stroke();
  doc.restore();
}

function drawFooter(doc, pageNum, pageCount) {
  doc.save();
  const footerY = PAGE_HEIGHT - MARGIN - 15;
  doc
    .fontSize(8)
    .fillColor(GRAY)
    .text("Generated by EAGLE — NCI Acquisition Assistant", MARGIN, footerY, {
      width: CONTENT_WIDTH / 2,
      align: "left",
      lineBreak: false,
    })
    .text(`Page ${pageNum} of ${pageCount}`, MARGIN + CONTENT_WIDTH / 2, footerY, {
      width: CONTENT_WIDTH / 2,
      align: "right",
      lineBreak: false,
    });
  doc.restore();
}

function drawWatermark(doc) {
  doc.save();
  doc.opacity(0.06);
  doc.fontSize(72);
  doc.fillColor(GRAY);
  // Diagonal watermark across center
  doc.translate(PAGE_WIDTH / 2, PAGE_HEIGHT / 2);
  doc.rotate(-45, { origin: [0, 0] });
  doc.text("DRAFT", -120, -30, { lineBreak: false });
  doc.restore();
}

function renderTokens(doc, tokens) {
  for (const token of tokens) {
    switch (token.type) {
      case "heading":
        renderHeading(doc, token);
        break;
      case "paragraph":
        renderParagraph(doc, token);
        break;
      case "table":
        renderTable(doc, token);
        break;
      case "list":
        renderList(doc, token);
        break;
      case "hr":
        renderHr(doc);
        break;
      case "space":
        doc.moveDown(0.5);
        break;
      case "code":
        renderCodeBlock(doc, token);
        break;
      case "blockquote":
        renderBlockquote(doc, token);
        break;
      default:
        // Skip unknown token types
        break;
    }
  }
}

function ensureSpace(doc, needed) {
  if (doc.y + needed > CONTENT_BOTTOM) {
    doc.addPage();
  }
}

function renderHeading(doc, token) {
  const depth = Math.min(token.depth, 4);
  const fontSize = HEADING_SIZES[depth] || 12;

  ensureSpace(doc, fontSize + 20);

  if (depth <= 2) doc.moveDown(0.5);

  doc
    .fontSize(fontSize)
    .fillColor(NCI_BLUE)
    .font("Helvetica-Bold")
    .text(token.text, { lineGap: 4 });

  doc.font("Helvetica").fillColor(BLACK).fontSize(BODY_SIZE);
  doc.moveDown(0.3);
}

function renderParagraph(doc, token) {
  ensureSpace(doc, 30);

  if (token.tokens && token.tokens.length > 0) {
    renderInlineTokens(doc, token.tokens);
  } else {
    doc
      .fontSize(BODY_SIZE)
      .font("Helvetica")
      .fillColor(BLACK)
      .text(token.text, { lineGap: BODY_SIZE * (LINE_HEIGHT - 1) });
  }
  doc.moveDown(0.4);
}

function renderInlineTokens(doc, tokens) {
  // Collect inline segments and render as a flowing paragraph
  const segments = flattenInlineTokens(tokens);

  doc.fontSize(BODY_SIZE);
  const options = { lineGap: BODY_SIZE * (LINE_HEIGHT - 1), continued: false };

  for (let i = 0; i < segments.length; i++) {
    const seg = segments[i];
    const isLast = i === segments.length - 1;

    const font =
      seg.bold && seg.italic
        ? "Helvetica-BoldOblique"
        : seg.bold
          ? "Helvetica-Bold"
          : seg.italic
            ? "Helvetica-Oblique"
            : "Helvetica";

    doc.font(font);
    doc.fillColor(seg.code ? [80, 80, 80] : BLACK);
    doc.text(seg.text, { ...options, continued: !isLast });
  }

  // Reset font
  doc.font("Helvetica").fillColor(BLACK);
}

function flattenInlineTokens(tokens) {
  const segments = [];
  for (const tok of tokens) {
    switch (tok.type) {
      case "text":
        segments.push({ text: tok.text, bold: false, italic: false, code: false });
        break;
      case "strong":
        if (tok.tokens) {
          for (const child of flattenInlineTokens(tok.tokens)) {
            segments.push({ ...child, bold: true });
          }
        } else {
          segments.push({ text: tok.text, bold: true, italic: false, code: false });
        }
        break;
      case "em":
        if (tok.tokens) {
          for (const child of flattenInlineTokens(tok.tokens)) {
            segments.push({ ...child, italic: true });
          }
        } else {
          segments.push({ text: tok.text, bold: false, italic: true, code: false });
        }
        break;
      case "codespan":
        segments.push({ text: tok.text, bold: false, italic: false, code: true });
        break;
      default:
        // For other inline types, extract raw text
        segments.push({ text: tok.raw || tok.text || "", bold: false, italic: false, code: false });
        break;
    }
  }
  return segments;
}

function renderTable(doc, token) {
  const headers = token.header.map((cell) => cellText(cell));
  const rows = token.rows.map((row) => row.map((cell) => cellText(cell)));
  const colCount = headers.length;

  if (colCount === 0) return;

  // Calculate column widths proportional to max content length
  const colMaxLen = headers.map((h, i) => {
    let max = h.length;
    for (const row of rows) {
      if (row[i] && row[i].length > max) max = row[i].length;
    }
    return max;
  });
  const totalLen = colMaxLen.reduce((a, b) => a + b, 0) || 1;
  const colWidths = colMaxLen.map((len) => {
    const w = Math.max(40, (len / totalLen) * CONTENT_WIDTH);
    return w;
  });
  // Normalize to fit content width
  const totalW = colWidths.reduce((a, b) => a + b, 0);
  const scale = CONTENT_WIDTH / totalW;
  for (let i = 0; i < colWidths.length; i++) colWidths[i] *= scale;

  const cellPadding = 4;
  const headerRowHeight = 22;
  const dataRowHeight = 18;

  // Check if table fits, otherwise add page
  const tableHeight = headerRowHeight + rows.length * dataRowHeight;
  ensureSpace(doc, Math.min(tableHeight, 200)); // At least header + a few rows

  doc.moveDown(0.3);

  // Draw header row
  let x = MARGIN;
  const headerY = doc.y;
  for (let i = 0; i < colCount; i++) {
    // Header cell background
    doc.save();
    doc.rect(x, headerY, colWidths[i], headerRowHeight).fill(NCI_BLUE);
    doc
      .fontSize(9)
      .font("Helvetica-Bold")
      .fillColor(WHITE)
      .text(headers[i], x + cellPadding, headerY + 5, {
        width: colWidths[i] - 2 * cellPadding,
        height: headerRowHeight,
        lineBreak: false,
      });
    doc.restore();
    x += colWidths[i];
  }

  doc.y = headerY + headerRowHeight;

  // Draw data rows
  for (let r = 0; r < rows.length; r++) {
    const rowY = doc.y;

    // Page break check — repeat header on new page
    if (rowY + dataRowHeight > CONTENT_BOTTOM) {
      doc.addPage();
      // Repeat header
      let hx = MARGIN;
      const hy = doc.y;
      for (let i = 0; i < colCount; i++) {
        doc.save();
        doc.rect(hx, hy, colWidths[i], headerRowHeight).fill(NCI_BLUE);
        doc
          .fontSize(9)
          .font("Helvetica-Bold")
          .fillColor(WHITE)
          .text(headers[i], hx + cellPadding, hy + 5, {
            width: colWidths[i] - 2 * cellPadding,
            height: headerRowHeight,
            lineBreak: false,
          });
        doc.restore();
        hx += colWidths[i];
      }
      doc.y = hy + headerRowHeight;
    }

    const currentRowY = doc.y;
    const bgColor = r % 2 === 0 ? WHITE : LIGHT_BLUE;

    x = MARGIN;
    for (let i = 0; i < colCount; i++) {
      doc.save();
      doc.rect(x, currentRowY, colWidths[i], dataRowHeight).fill(bgColor);
      doc
        .fontSize(9)
        .font("Helvetica")
        .fillColor(BLACK)
        .text(rows[r]?.[i] || "", x + cellPadding, currentRowY + 4, {
          width: colWidths[i] - 2 * cellPadding,
          height: dataRowHeight,
          lineBreak: false,
        });
      doc.restore();
      x += colWidths[i];
    }

    doc.y = currentRowY + dataRowHeight;
  }

  doc.font("Helvetica").fillColor(BLACK).fontSize(BODY_SIZE);
  doc.moveDown(0.5);
}

function cellText(cell) {
  if (typeof cell === "string") return cell;
  if (cell.text) return cell.text;
  if (cell.tokens) return cell.tokens.map((t) => t.text || t.raw || "").join("");
  return "";
}

function renderList(doc, token) {
  const ordered = token.ordered;
  const items = token.items || [];

  for (let i = 0; i < items.length; i++) {
    const item = items[i];
    ensureSpace(doc, 20);

    const prefix = ordered ? `${i + 1}. ` : "•  ";
    const indent = 20;
    let text = "";

    // Handle checkbox items
    if (item.checked === true) {
      text = "☑ " + extractItemText(item);
    } else if (item.checked === false) {
      text = "☐ " + extractItemText(item);
    } else {
      text = extractItemText(item);
    }

    doc
      .fontSize(BODY_SIZE)
      .font("Helvetica")
      .fillColor(BLACK)
      .text(prefix + text, MARGIN + indent, doc.y, {
        width: CONTENT_WIDTH - indent,
        lineGap: BODY_SIZE * (LINE_HEIGHT - 1),
      });
  }

  doc.moveDown(0.3);
}

function extractItemText(item) {
  if (item.tokens) {
    return item.tokens
      .map((t) => {
        if (t.type === "text") return t.text;
        if (t.type === "paragraph" && t.tokens) {
          return t.tokens.map((tt) => tt.text || tt.raw || "").join("");
        }
        return t.text || t.raw || "";
      })
      .join("");
  }
  return item.text || "";
}

function renderHr(doc) {
  ensureSpace(doc, 15);
  doc.moveDown(0.3);
  doc
    .moveTo(MARGIN, doc.y)
    .lineTo(PAGE_WIDTH - MARGIN, doc.y)
    .strokeColor(LIGHT_GRAY)
    .lineWidth(0.5)
    .stroke();
  doc.moveDown(0.5);
}

function renderCodeBlock(doc, token) {
  const lines = (token.text || "").split("\n");
  const blockHeight = lines.length * 13 + 16;

  ensureSpace(doc, Math.min(blockHeight, 150));

  const codeY = doc.y;
  doc.save();
  doc.rect(MARGIN, codeY, CONTENT_WIDTH, blockHeight).fill([245, 245, 245]);
  doc
    .fontSize(9)
    .font("Courier")
    .fillColor([60, 60, 60])
    .text(token.text, MARGIN + 8, codeY + 8, {
      width: CONTENT_WIDTH - 16,
    });
  doc.restore();

  doc.y = codeY + blockHeight + 4;
  doc.font("Helvetica").fillColor(BLACK).fontSize(BODY_SIZE);
}

function renderBlockquote(doc, token) {
  ensureSpace(doc, 30);

  const text = token.tokens
    ? token.tokens.map((t) => t.text || t.raw || "").join("\n")
    : token.text || "";

  const quoteX = MARGIN + 12;
  const quoteY = doc.y;

  doc.save();
  // Left bar
  doc
    .moveTo(MARGIN + 4, quoteY)
    .lineTo(MARGIN + 4, quoteY + 30)
    .strokeColor(NCI_BLUE)
    .lineWidth(2)
    .stroke();
  doc
    .fontSize(BODY_SIZE)
    .font("Helvetica-Oblique")
    .fillColor([80, 80, 80])
    .text(text, quoteX, quoteY, {
      width: CONTENT_WIDTH - 20,
      lineGap: BODY_SIZE * (LINE_HEIGHT - 1),
    });
  doc.restore();

  doc.font("Helvetica").fillColor(BLACK).fontSize(BODY_SIZE);
  doc.moveDown(0.5);
}
